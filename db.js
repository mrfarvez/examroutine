const { Pool } = require('pg');

let pool = null;
let schemaPromise = null;

function getPool() {
  if (!pool) {
    const cs = process.env.DATABASE_URL;
    if (!cs) throw new Error('DATABASE_URL is not set');
    const needsSsl = /neon\.tech|sslmode=require/i.test(cs);
    pool = new Pool({
      connectionString: cs,
      ssl: needsSsl ? { rejectUnauthorized: false } : undefined,
      max: 5,
      idleTimeoutMillis: 30000,
      connectionTimeoutMillis: 15000
    });
    pool.on('error', () => {});
  }
  return pool;
}

const SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS admin_users (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  username TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS exam_sessions (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name TEXT NOT NULL,
  term TEXT,
  status TEXT NOT NULL DEFAULT 'draft',
  created_at TEXT NOT NULL DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS exam_entries (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  session_id INTEGER NOT NULL REFERENCES exam_sessions(id) ON DELETE CASCADE,
  course_code TEXT,
  course_title TEXT,
  teacher_initial TEXT,
  section TEXT NOT NULL,
  exam_date TEXT,
  time_slot TEXT,
  room TEXT,
  seats INTEGER,
  roll_start INTEGER,
  roll_end INTEGER,
  source TEXT DEFAULT 'seatplan',
  created_at TEXT NOT NULL DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS routine_entries (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  session_id INTEGER REFERENCES exam_sessions(id) ON DELETE CASCADE,
  course_code TEXT,
  course_title TEXT,
  section TEXT,
  teacher_initial TEXT,
  created_at TEXT NOT NULL DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS uploads (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  session_id INTEGER REFERENCES exam_sessions(id) ON DELETE CASCADE,
  type TEXT NOT NULL,
  original_filename TEXT,
  parsed_row_count INTEGER DEFAULT 0,
  status TEXT DEFAULT 'parsed',
  uploaded_at TEXT NOT NULL DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX IF NOT EXISTS idx_entries_section ON exam_entries(section);
CREATE INDEX IF NOT EXISTS idx_entries_session ON exam_entries(session_id);
ALTER TABLE exam_entries ADD COLUMN IF NOT EXISTS seats INTEGER;
`;

function ensureSchema() {
  if (!schemaPromise) {
    schemaPromise = getPool()
      .query(SCHEMA_SQL)
      .catch((e) => { schemaPromise = null; throw e; });
  }
  return schemaPromise;
}

async function query(text, params) {
  await ensureSchema();
  const res = await getPool().query(text, params);
  return res.rows;
}

async function get(text, params) {
  const rows = await query(text, params);
  return rows[0];
}

async function run(text, params) {
  await ensureSchema();
  const res = await getPool().query(text, params);
  return { changes: res.rowCount };
}

async function insertReturningId(text, params) {
  const rows = await query(text, params);
  return rows[0] ? rows[0].id : null;
}

async function transaction(fn) {
  await ensureSchema();
  const client = await getPool().connect();
  try {
    await client.query('BEGIN');
    const out = await fn(client);
    await client.query('COMMIT');
    return out;
  } catch (e) {
    try { await client.query('ROLLBACK'); } catch (_) {}
    throw e;
  } finally {
    client.release();
  }
}

module.exports = { getPool, ensureSchema, query, get, run, insertReturningId, transaction };
